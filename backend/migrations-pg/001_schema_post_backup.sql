CREATE TABLE IF NOT EXISTS entrepot (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    structur_id   bigint       NOT NULL,
    libelle       varchar(150) NOT NULL,
    code          varchar(50),
    adresse       varchar(255),
    type_entrepot varchar(10)  NOT NULL DEFAULT 'REEL'
                  CHECK (type_entrepot IN ('REEL','FICTIF','MAD','PRIVE','PUBLIC','AUTRE')),
    created_at    timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    timestamp,
    deleted_at    timestamp
);
CREATE INDEX IF NOT EXISTS entrepot_idx_structur ON entrepot (structur_id);
CREATE INDEX IF NOT EXISTS entrepot_idx_deleted  ON entrepot (deleted_at);

CREATE TABLE IF NOT EXISTS sommier (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    structur_id             bigint NOT NULL,
    iddossiers              bigint,
    idclients               bigint,
    idregimedeclaration     bigint NOT NULL,
    numero_declaration      varchar(100) NOT NULL UNIQUE,
    date_declaration        date NOT NULL,
    date_echeance           date NOT NULL,
    caution_requise         smallint NOT NULL DEFAULT 0,
    caution_montant         numeric(15,2),
    caution_liberee         smallint NOT NULL DEFAULT 0,
    caution_date_liberation date,
    statut                  varchar(10) NOT NULL DEFAULT 'ACTIF'
                            CHECK (statut IN ('ACTIF','APURE','EXPIRE','RESILIE')),
    date_apurement_total    date,
    observations            text,
    created_by              bigint,
    created_at              timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              timestamp,
    deleted_at              timestamp
);
CREATE INDEX IF NOT EXISTS sommier_idx_structur ON sommier (structur_id);
CREATE INDEX IF NOT EXISTS sommier_idx_client   ON sommier (idclients);
CREATE INDEX IF NOT EXISTS sommier_idx_regime   ON sommier (idregimedeclaration);
CREATE INDEX IF NOT EXISTS sommier_idx_dossier  ON sommier (iddossiers);
CREATE INDEX IF NOT EXISTS sommier_idx_echeance ON sommier (date_echeance);
CREATE INDEX IF NOT EXISTS sommier_idx_statut   ON sommier (statut);
CREATE INDEX IF NOT EXISTS sommier_idx_deleted  ON sommier (deleted_at);

CREATE TABLE IF NOT EXISTS sommier_article (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sommier_id     bigint NOT NULL REFERENCES sommier (id) ON DELETE CASCADE,
    entrepot_id    bigint NOT NULL REFERENCES entrepot (id) ON DELETE RESTRICT,
    numero_ligne   integer,
    designation    varchar(255) NOT NULL,
    code_tarif     varchar(20),
    poids_initial  numeric(15,3) NOT NULL DEFAULT 0,
    colis_initial  integer       NOT NULL DEFAULT 0,
    valeur_initial numeric(15,2) NOT NULL DEFAULT 0,
    unite_poids    varchar(10)   NOT NULL DEFAULT 'KG',
    poids_apure    numeric(15,3) NOT NULL DEFAULT 0,
    colis_apure    integer       NOT NULL DEFAULT 0,
    valeur_apure   numeric(15,2) NOT NULL DEFAULT 0,
    created_at     timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS sommier_article_idx_sommier  ON sommier_article (sommier_id);
CREATE INDEX IF NOT EXISTS sommier_article_idx_entrepot ON sommier_article (entrepot_id);
CREATE INDEX IF NOT EXISTS sommier_article_idx_tarif    ON sommier_article (code_tarif);

CREATE TABLE IF NOT EXISTS apurement (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sommier_id       bigint NOT NULL REFERENCES sommier (id) ON DELETE CASCADE,
    structur_id      bigint NOT NULL,
    date_apurement   date NOT NULL,
    type_sortie      varchar(20) NOT NULL
                     CHECK (type_sortie IN ('REEXPORTATION','MISE_A_CONSOMMATION','DESTRUCTION','TRANSFERT','AUTRE')),
    reference_sortie varchar(150),
    observations     text,
    created_by       bigint,
    created_at       timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       timestamp,
    deleted_at       timestamp
);
CREATE INDEX IF NOT EXISTS apurement_idx_sommier  ON apurement (sommier_id);
CREATE INDEX IF NOT EXISTS apurement_idx_structur ON apurement (structur_id);
CREATE INDEX IF NOT EXISTS apurement_idx_date     ON apurement (date_apurement);
CREATE INDEX IF NOT EXISTS apurement_idx_deleted  ON apurement (deleted_at);

CREATE TABLE IF NOT EXISTS apurement_ligne (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apurement_id       bigint NOT NULL REFERENCES apurement (id) ON DELETE CASCADE,
    sommier_article_id bigint NOT NULL REFERENCES sommier_article (id) ON DELETE RESTRICT,
    poids              numeric(15,3) NOT NULL DEFAULT 0,
    colis              integer       NOT NULL DEFAULT 0,
    valeur             numeric(15,2) NOT NULL DEFAULT 0,
    created_at         timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS apurement_ligne_idx_apurement ON apurement_ligne (apurement_id);
CREATE INDEX IF NOT EXISTS apurement_ligne_idx_article   ON apurement_ligne (sommier_article_id);

CREATE TABLE IF NOT EXISTS sommier_alert_log (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sommier_id    bigint NOT NULL REFERENCES sommier (id) ON DELETE CASCADE,
    horizon_days  integer NOT NULL,
    alert_date    date NOT NULL,
    email_sent_to varchar(255),
    sent_at       timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (sommier_id, horizon_days, alert_date)
);
CREATE INDEX IF NOT EXISTS sommier_alert_log_idx_sommier ON sommier_alert_log (sommier_id);

-- ON UPDATE CURRENT_TIMESTAMP de MySQL (fonction créée par la migration des données)
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['entrepot', 'sommier', 'apurement'] LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_updated_at ON %1$I', t);
    EXECUTE format('CREATE TRIGGER trg_%1$s_updated_at BEFORE UPDATE ON %1$I
                    FOR EACH ROW EXECUTE FUNCTION set_on_update_timestamp(''updated_at'')', t);
  END LOOP;
END $$;

